import math

print("=== โปรแกรมคำนวณพื้นที่และปริมาตร ===")
print("1. พื้นที่สี่เหลี่ยมมุมฉาก")
print("2. พื้นที่วงกลม")
print("3. ปริมาตรลูกบาศก์")
print("4. ปริมาตรทรงกระบอก")

เลือก = int(input("เลือกเมนู (1-4): "))

if เลือก == 1:
    กว้าง = float(input("กรอกความกว้าง: "))
    ยาว = float(input("กรอกความยาว: "))
    พื้นที่ = กว้าง * ยาว
    print("พื้นที่สี่เหลี่ยมมุมฉาก =", พื้นที่)

elif เลือก == 2:
    รัศมี = float(input("กรอกรัศมี: "))
    พื้นที่ = math.pi * (รัศมี ** 2)
    print("พื้นที่วงกลม =", round(พื้นที่, 2))

elif เลือก == 3:
    ด้าน = float(input("กรอกความยาวด้าน: "))
    ปริมาตร = ด้าน ** 3
    print("ปริมาตรลูกบาศก์ =", ปริมาตร)

elif เลือก == 4:
    รัศมี = float(input("กรอกรัศมี: "))
    สูง = float(input("กรอกความสูง: "))
    ปริมาตร = math.pi * (รัศมี ** 2) * สูง
    print("ปริมาตรทรงกระบอก =", round(ปริมาตร, 2))

else:
    print("กรุณาเลือกเมนู 1-4")